"""Пересобирает docs/TEST_SCENARIOS.md: прогоняет сценарии через систему (расчётное время 19:00)."""
import sys; sys.path.insert(0, ".")
from datetime import datetime
from rag import retrieve, generate, TZ
HERE = {"Mega Silk Way": ("silk way", "батыр даңғылы 62", "батыр, 62"), "Хан Шатыр": ("тұран даңғылы 37", "туран, 37", "туран даңғылы 37")}
S = [("Сценарий 1 (пользовательский)", "Популярное кафе с видом на город", "Байтерек", (51.1283, 71.4305), 90, 1),
     ("Сценарий 2 (пользовательский)", "Хочу что-то связанное с адреналином", "Хан Шатыр", (51.1325, 71.4039), 120, 3),
     ("Сценарий 3 (пользовательский)", "Места, где можно прийти с собакой", "EXPO", (51.0894, 71.4167), 90, 1),
     ("Сценарий 4 (из ТЗ)", "Я сейчас возле Mega Silk Way, хочу прогуляться 30–60 минут — что посоветуете?", "Mega Silk Way", (51.0891, 71.4073), 60, 1),
     ("Сценарий 5 (из ТЗ)", "Хочу тихое место с кофе и розеткой недалеко от меня", "Mega Silk Way", (51.0891, 71.4073), 60, 1),
     ("Сценарий 6 (из ТЗ)", "Еду с ребёнком — где рядом есть детские площадки или музеи с интерактивами?", "Байтерек", (51.1283, 71.4305), 120, 3),
     ("Сценарий 7 (из ТЗ)", "Я турист, у меня 2 часа перед вылетом: что можно посмотреть поблизости?", "Байтерек", (51.1283, 71.4305), 120, 1),
     ("Сценарий 8 (из ТЗ)", "Ищу необычную ночную активность (последние пару часов)", "Хан Шатыр", (51.1325, 71.4039), 120, 2)]
now = datetime.now(TZ).replace(hour=19, minute=0, second=0, microsecond=0)
out = ["# Тестовые сценарии и фактические ответы системы\n",
       f"_Ответы получены автоматически (расчётное время запроса: {now:%Y-%m-%d %H:%M}, Астана). Режим без LLM (шаблон); с `GEMINI_API_KEY` тот же контекст отдаётся Gemini. "
       "Настройки по умолчанию: радиус 2 км, в выдаче места с оценкой 2GIS. Время суток учитывается при ранжировании: места, не работающие по известным часам, понижаются._\n"]
for title, q, place, (la, lo), mins, grp in S:
    res = retrieve(q, la, lo, 2.0, k=8, now=now, only_rated=True, group=grp, here=HERE.get(place, ()))
    out.append(f"## {title}\n\n**Вход:** «{q}»  \n**Контекст:** я возле «{place}», времени {mins} мин, компания {grp} чел.\n")
    out.append("**Ожидаемый тип ответа:** 1–3 пункта: почему подходит, что делать, источник данных, честные пометки о том, чего в данных нет.\n")
    out.append("**Фактический ответ:**\n")
    out.append("\n".join("> " + l if l.strip() else ">" for l in generate(q, mins, res, now, grp).split("\n")))
    out.append("")
open("docs/TEST_SCENARIOS.md", "w").write("\n".join(out))
print("ok")
