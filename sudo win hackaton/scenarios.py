def hours_flags(hours):
    """(круглосуточно, до поздней ночи, с утра) по строке часов."""
    from rag import parse_hours
    if hours == "круглосуточно":
        return True, True, True
    rules = parse_hours(hours.replace("24:00", "00:00")) if hours and not hours.startswith("уточнить") else None
    if not rules:
        return False, False, False
    late = any(b < a for _, a, b in rules)  # закрывается после полуночи
    early = any(a <= 8 * 60 for _, a, b in rules)
    return False, late, early


