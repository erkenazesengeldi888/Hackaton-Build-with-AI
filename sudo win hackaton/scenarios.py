def _covers(hours, minute, cats_ok, category):
    """Работает ли место в указанную минуту суток (по часам); False, если часов нет."""
    from rag import parse_hours
    if category not in cats_ok or not hours or hours.startswith("уточнить"):
        return False
    if hours == "круглосуточно":
        return True
    rules = parse_hours(hours.replace("24:00", "00:00"))
    return bool(rules) and any((a <= minute < b) if a < b else (minute >= a or minute < b) for _, a, b in rules)


def ui_tags(p, lrt_m=None):
    """Понятные теги для карточек: тип места, особенности, время суток, расположение, рейтинг и популярность."""
    t, L = set(p["tags"]), []
    L.append(CAT_TAG.get(p["category"], p["category"].capitalize()))
    L += [v for k, v in _CUISINE.items() if k in t][:2]
    if t & {"вид", "вид на город", "панорама", "высокий этаж"}: L.append("С видом")
    if t & {"терраса", "веранда"}: L.append("Терраса")
    if "праздник" in t: L.append("Для праздника"); L.append("Для компании")
    if t & {"адреналин", "картинг", "дрифт"}: L.append("Адреналин")
    if t & {"с собакой", "площадка для собак"}: L.append("С собакой")
    if "доступно для колясок" in t: L.append("Доступно")
    if "wifi" in t: L.append("Wi-Fi")
    if "с собой" in t: L.append("С собой")
    if "живая музыка" in t: L.append("Живая музыка")
    if t & {"дети", "семья"}: L.append("С детьми")
    hrs, cat = p.get("hours") or "", p["category"]
    full, late, early = hours_flags(hrs)
    if full: L.append("Круглосуточно")
    elif late: L.append("До поздней ночи")
    if early and not full: L.append("С утра")
    if _covers(hrs, 9 * 60, ("кофейня", "ресторан", "фастфуд"), cat): L.append("Завтрак")
    if _covers(hrs, 13 * 60, ("кофейня", "ресторан", "фастфуд", "кулинария"), cat): L.append("Обед")
    if _covers(hrs, 20 * 60, ("ресторан", "бар", "кофейня"), cat): L.append("Ужин")
    addr = (p.get("address") or "").lower()
    if any(x in addr for x in ("mega", "трц", "mall", "plaza", "asia park", "шатыр")) or cat == "тц": L.append("В ТРЦ")
    if lrt_m is not None and lrt_m <= 500: L.append("Рядом ЛРТ")
    rv, rt = p.get("reviews") or 0, p.get("rating") or 0
    if rt >= 4.5 and rt < 4.8: L.append("Рейтинг 4,5+")
    if rt >= 4.8: L.append("Рейтинг 4,8+")
    if rv >= 5000: L.append("5000+ оценок")
    elif rv >= 1000: L.append("1000+ оценок")
    elif rv >= 500: L.append("500+ оценок")
    return list(dict.fromkeys(L))


