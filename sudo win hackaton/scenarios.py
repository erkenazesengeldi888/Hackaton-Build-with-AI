def weather_summary(w):
    """(плохая_погода, текст) по текущей погоде Open-Meteo."""
    if not w:
        return False, ""
    t, wind, pr, code = w["t"], w["wind"], w.get("pr", 0) or 0, w.get("code", 0) or 0
    bad = t <= -5 or wind >= 10 or pr >= 0.2 or code >= 51
    why = []
    if t <= -5: why.append("мороз")
    if wind >= 10: why.append("сильный ветер")
    if pr >= 0.2 or code >= 51: why.append("осадки")
    sign = "−" if t < 0 else ""
    head = f"Сейчас в Астане {sign}{abs(round(t))}°C, ветер {wind:.0f} м/с"
    return bad, head + (f" ({', '.join(why)}) → выше тёплые заведения" if bad else " → хорошая погода для прогулки")


